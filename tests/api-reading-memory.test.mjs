const directory=await fs.mkdtemp(path.join(os.tmpdir(),'ra-reading-memory-'));
process.env.RA_DATA_DIR=directory;process.env.DEEPSEEK_API_KEY='test-only-key';
const originalFetch=globalThis.fetch;
